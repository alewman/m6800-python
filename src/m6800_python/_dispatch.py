MODES = {
    None: None,
    "imm8": "_ea_imm8",
    "imm16": "_ea_imm16",
    "dir": "_ea_dir",
    "idx": "_ea_idx",
    "ext": "_ea_ext",
}

Entry = tuple[Callable, Callable | None, int]


def build_table(cls: type, part: int, undocumented: Callable[[int], Entry]) -> list[Entry]:
    """Return the 256 dispatch entries of ``cls`` for part 6800 or 6801.

    ``undocumented(opcode)`` supplies the entry for every opcode the part's
    manual does not assign (see _undocumented.py).
    """
    table: list[Entry] = []
    for opcode in range(256):
        handler, mode, cycles_6800, cycles_6801 = OPCODES.get(opcode, (None, None, None, None))
        cycles = cycles_6800 if part == 6800 else cycles_6801
        if cycles is None:
            table.append(undocumented(opcode))
            continue
        ea = getattr(cls, MODES[mode]) if mode else None
        table.append((getattr(cls, "_op_" + handler), ea, cycles))
    return table
